package questions;

public class AddTwoNum {
    static int addTwoNumber(int num1, int num2) {
        int sum = num1+ num2;
        return sum;
    }
    public static void main(String arg[]) {
        int num1 = 10;
        int num2 = 20;
        System.out.println(addTwoNumber(num1, num2));
    }
}
